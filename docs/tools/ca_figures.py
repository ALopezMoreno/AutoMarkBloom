"""Docs helper: turns a ca-trace JSON (see tools/ca-trace) into the TikZ
figures of the worked automaton example in sections/automaton.tex.

Usage: python3 ca_figures.py trace.json ../figures
"""
import json, math, sys

d = json.load(open(sys.argv[1]))
OUT = sys.argv[2]
NA, NP = d['na'], d['np']
t = d['traits']
LAYER = 2  # the layer followed step by step
SWEEPS = [0, 3, 8, 15, 25, None]  # None: the final sweep

COLOURS = ['petA', 'petB', 'petC', 'petD', 'petE', 'petF', 'petG', 'petH']
PALETTE = r'''\definecolor{petA}{HTML}{C8507A}\definecolor{petB}{HTML}{3F7FBF}
\definecolor{petC}{HTML}{E0A030}\definecolor{petD}{HTML}{4E9A5B}
\definecolor{petE}{HTML}{8A5CB8}\definecolor{petF}{HTML}{D2693C}
\definecolor{petG}{HTML}{3AA6A0}\definecolor{petH}{HTML}{8C8C3A}'''

def first_id(k):
    return min(e['petal'] for e in d['layers'][k]['events']) if d['layers'][k]['events'] else 0

def grid_tikz(g, k, w, h, x0=0.0, y0=0.0, mark=True):
    """Run-length rectangles for one NP x NA grid, cell size w x h (cm)."""
    base = first_id(k)
    out = [rf'\draw[black!25, fill=black!4] ({x0:.3f},{y0:.3f}) rectangle ({x0+NA*w:.3f},{y0+NP*h:.3f});']
    for r in range(NP):
        s = 0
        while s < NA:
            p = g[r*NA+s]
            e = s
            while e < NA and g[r*NA+e] == p:
                e += 1
            if p >= 0:
                c = COLOURS[(p-base) % len(COLOURS)]
                out.append(rf'\fill[{c}] ({x0+s*w:.3f},{y0+r*h:.3f}) rectangle ({x0+e*w:.3f},{y0+(r+1)*h:.3f});')
            s = e
    if mark:
        for ev in d['layers'][k]['events']:
            s = ev['cell']
            out.append(rf'\draw[black, line width=0.5pt] ({x0+s*w:.3f},{y0:.3f}) rectangle ({x0+(s+1)*w:.3f},{y0+h:.3f});')
    return '\n'.join(out)

def write(name, body):
    open(f'{OUT}/{name}.tex', 'w').write(f'% Generated by tools/ca_figures.py from seed {d["seed"]}, flower {d["flower"]}. Do not edit.\n' + body + '\n')

# 1. Inhibition profile on row 0 of the followed layer.
L = d['layers'][LAYER]
X = 12.0 / NA; Y = 2.4
def curve(vals):
    return ' '.join(f'({(s+0.5)*X:.3f},{min(v,1.6)*Y:.3f})' for s, v in enumerate(vals))
lines = [r'\begin{tikzpicture}[font=\footnotesize]', PALETTE]
lines.append(rf'\draw[->] (0,0) -- ({NA*X+0.3:.2f},0) node[right] {{$\theta$}};')
lines.append(rf'\draw[->] (0,0) -- (0,{1.6*Y+0.3:.2f}) node[above] {{$I_{LAYER}(\theta)$}};')
for deg in range(0, 361, 90):
    x = deg/360*NA*X
    lines.append(rf'\draw ({x:.3f},0) -- ({x:.3f},-0.08) node[below] {{${deg}^\circ$}};')
for v in (0.5, 1.0, 1.5):
    lines.append(rf'\draw (0,{v*Y:.3f}) -- (-0.08,{v*Y:.3f}) node[left] {{{v}}};')
tau = t['inhibit_threshold']
lines.append(rf'\draw[black!60, dashed] (0,{tau*Y:.3f}) -- ({NA*X:.3f},{tau*Y:.3f}) node[right, black] {{$\tau={tau:.2f}$}};')
lines.append(rf'\fill[black!8] plot coordinates {{{curve(L["below"])}}} -- ({NA*X:.3f},0) -- (0,0) -- cycle;')
lines.append(rf'\draw[black!50] plot coordinates {{{curve(L["below"])}}};')
lines.append(rf'\draw[thick, petA!70!black] plot coordinates {{{curve(L["after_pass"][-1])}}};')
for i, ev in enumerate(L['events']):
    x = (ev['cell']+0.5)*X
    c = COLOURS[(ev['petal']-first_id(LAYER)) % len(COLOURS)]
    lines.append(rf'\fill[{c}] ({x:.3f},0) circle (2.2pt); \node[above, inner sep=1pt] at ({x:.3f},0.12) {{\textbf{{{i+1}}}}};')
lines.append(r'\end{tikzpicture}')
write('ca-inhibition', '\n'.join(lines))

# 2. Primordia of every layer on concentric rings.
lines = [r'\begin{tikzpicture}[font=\scriptsize]', PALETTE]
for k, Lk in enumerate(d['layers']):
    R = 0.9 + 0.32*k
    lines.append(rf'\draw[black!20] (0,0) circle ({R:.2f});')
    col = 'petA' if k % 2 == 0 else 'petB'
    for ev in Lk['events']:
        th = (ev['cell']+0.5)*360/NA
        lines.append(rf'\fill[{col}] ({th:.2f}:{R:.2f}) circle (2.1pt);')
    lines.append(rf'\node[fill=white, inner sep=0.6pt] at (-90:{R:.2f}) {{\tiny {k}}};')
lines.append(r'\node[align=center] at (0,0) {core};')
lines.append(r'\fill[petA] (2.4,-3.9) circle (2.1pt) node[right, black] {even layer};')
lines.append(r'\fill[petB] (2.4,-4.3) circle (2.1pt) node[right, black] {odd layer};')
lines.append(r'\end{tikzpicture}')
write('ca-rings', '\n'.join(lines))

# 3. Growth sweeps of the followed layer.
w, h = 0.062, 0.062
last = len(L['sweeps'])-1
lines = [r'\begin{tikzpicture}[font=\footnotesize]', PALETTE]
for i, sw in enumerate(SWEEPS):
    n = last if sw is None else sw
    col, row = i % 2, i // 2
    x0, y0 = col*(NA*w+0.7), -row*(NP*h+0.75)
    lines.append(grid_tikz(L['sweeps'][n], LAYER, w, h, x0, y0))
    filled = sum(1 for v in L['sweeps'][n] if v >= 0)
    label = f'sweep {n}' + (' (final)' if sw is None else '') + f', {filled} cells owned'
    lines.append(rf'\node[above right, inner sep=1pt] at ({x0:.3f},{y0+NP*h:.3f}) {{{label}}};')
lines.append(r'\end{tikzpicture}')
write('ca-sweeps', '\n'.join(lines))

# 4. Final grid of every layer.
w, h = 0.04, 0.04
lines = [r'\begin{tikzpicture}[font=\footnotesize]', PALETTE]
for k, Lk in enumerate(d['layers']):
    col, row = k % 2, k // 2
    x0, y0 = col*(NA*w+0.6), -row*(NP*h+0.6)
    lines.append(grid_tikz(Lk['sweeps'][-1], k, w, h, x0, y0, mark=False))
    lines.append(rf'\node[above right, inner sep=1pt] at ({x0:.3f},{y0+NP*h:.3f}) {{layer {k}: {len(Lk["events"])} petals}};')
lines.append(r'\end{tikzpicture}')
write('ca-layers', '\n'.join(lines))
print('wrote 4 figures')
